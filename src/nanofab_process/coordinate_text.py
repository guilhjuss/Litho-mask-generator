"""Small polygon font shared with the browser coordinate-label design."""
import math

GLYPHS = {'0': ['01110', '10001', '10011', '10101', '11001', '10001', '01110'], '1': ['00100', '01100', '00100', '00100', '00100', '00100', '01110'], '2': ['01110', '10001', '00001', '00010', '00100', '01000', '11111'], '3': ['11110', '00001', '00001', '01110', '00001', '00001', '11110'], '4': ['00010', '00110', '01010', '10010', '11111', '00010', '00010'], '5': ['11111', '10000', '10000', '11110', '00001', '00001', '11110'], '6': ['01110', '10000', '10000', '11110', '10001', '10001', '01110'], '7': ['11111', '00001', '00010', '00100', '01000', '01000', '01000'], '8': ['01110', '10001', '10001', '01110', '10001', '10001', '01110'], '9': ['01110', '10001', '10001', '01111', '00001', '00001', '01110'], 'X': ['10001', '10001', '01010', '00100', '01010', '10001', '10001'], 'Y': ['10001', '10001', '01010', '00100', '00100', '00100', '00100'], '=': ['00000', '00000', '11111', '00000', '11111', '00000', '00000'], '-': ['00000', '00000', '00000', '11111', '00000', '00000', '00000'], '.': ['00000', '00000', '00000', '00000', '00000', '00110', '00110'], 'u': ['00000', '00000', '10001', '10001', '10001', '10011', '01101'], 'm': ['00000', '00000', '11010', '10101', '10101', '10101', '10101'], ' ': ['00000', '00000', '00000', '00000', '00000', '00000', '00000']}

def format_coordinate(value):
    rounded = math.floor(value * 1000 + 0.5) / 1000
    return format(rounded, ".3f").rstrip("0").rstrip(".") if rounded else "0"

def coordinate_rectangles(x, y, height):
    size = height / 7
    rectangles = []
    lines = ("X=" + format_coordinate(x) + " um", "Y=" + format_coordinate(y) + " um")
    for line, text in enumerate(lines):
        for i, char in enumerate(text):
            for row, bitmap in enumerate(GLYPHS[char]):
                column = 0
                while column < 5:
                    if bitmap[column] != "1":
                        column += 1
                        continue
                    start = column
                    while column < 5 and bitmap[column] == "1":
                        column += 1
                    rectangles.append((i * 6 * size + start * size,
                                       -line * 9 * size + (6 - row) * size,
                                       i * 6 * size + column * size,
                                       -line * 9 * size + (7 - row) * size))
    return rectangles
